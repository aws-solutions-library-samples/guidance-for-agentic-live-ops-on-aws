import "@aws-amplify/ui-react/styles.css";
import SideNavigation from "@cloudscape-design/components/side-navigation";
import Box from "@cloudscape-design/components/box";
import Button from "@cloudscape-design/components/button";
import SpaceBetween from "@cloudscape-design/components/space-between";
import "@cloudscape-design/global-styles/index.css";
import { useNavigate, useLocation } from "react-router-dom";
import { useConversations } from "../../contexts/ConversationsContext";

const SideBar = () => {
    const navigate = useNavigate();
    const location = useLocation();
    const { conversations, activeId, load, remove, newChat } = useConversations();

    const handleNew = () => {
        newChat();
        navigate("/");
    };

    const handleLoad = async (id: string) => {
        await load(id);
        navigate("/");
    };

    return (
        <SpaceBetween direction="vertical" size="s">
            <Box padding="s">
                <SideNavigation
                    activeHref={location.pathname}
                    onFollow={(e) => {
                        if (!e.detail.external) {
                            e.preventDefault();
                            navigate(e.detail.href);
                        }
                    }}
                    items={[
                        { type: "link" as const, text: "Chat", href: "/" },
                        { type: "link" as const, text: "Real-Time Monitoring", href: "/monitor" },
                    ]}
                />
            </Box>

            {location.pathname === "/" && (
                <>
                    <hr
                        style={{
                            margin: "0 16px",
                            border: "none",
                            borderTop: "1px solid rgba(0,0,0,0.1)",
                        }}
                    />
                    <Box padding={{ horizontal: "s" }}>
                        <Button variant="primary" iconName="add-plus" onClick={handleNew} fullWidth>
                            New Chat
                        </Button>
                    </Box>
                </>
            )}

            {location.pathname === "/monitor" && (
                <>
                    <Box padding={{ horizontal: "s" }}>
                        <SpaceBetween direction="vertical" size="xs">
                            <Box variant="h4">Dashboard Guide</Box>

                            {[
                                {
                                    icon: "📊",
                                    title: "KPI Cards",
                                    desc: "Total events ingested in the selected time window, broken down by platform and region. Click to see full breakdowns.",
                                },
                                {
                                    icon: "📈",
                                    title: "Event Timeline",
                                    desc: "Live line chart showing event volume over time per event type. Use the time range selector to zoom in or out.",
                                },
                                {
                                    icon: "⚡",
                                    title: "Live Metrics & Thresholds",
                                    desc: "Each monitored event type with its current count vs configured threshold. Red = threshold exceeded, yellow = approaching. Click configure to adjust thresholds or enable auto-reports.",
                                },
                                {
                                    icon: "🤖",
                                    title: "Generate AI Analysis",
                                    desc: "Triggers the AI agent to analyze a specific metric — checks live data, historical patterns, and knowledge base to produce a root cause report.",
                                },
                                {
                                    icon: "📋",
                                    title: "AI Analysis Reports",
                                    desc: "Reports generated by the AI agent. Each includes severity, root cause analysis, and remediation recommendations. Use 'Send to Chat' to continue the investigation in the chat assistant.",
                                },
                            ].map(({ icon, title, desc }) => (
                                <div
                                    key={title}
                                    style={{
                                        paddingBottom: 8,
                                        borderBottom: "1px solid rgba(0,0,0,0.06)",
                                    }}
                                >
                                    <div style={{ fontSize: 13, fontWeight: 600, marginBottom: 2 }}>
                                        {icon} {title}
                                    </div>
                                    <div
                                        style={{ fontSize: 12, color: "#687078", lineHeight: 1.5 }}
                                    >
                                        {desc}
                                    </div>
                                </div>
                            ))}
                        </SpaceBetween>
                    </Box>
                </>
            )}

            {location.pathname === "/" && conversations.length > 0 && (
                <Box padding={{ horizontal: "s" }}>
                    <SpaceBetween direction="vertical" size="xxs">
                        <Box variant="h4" padding={{ bottom: "xxs" }}>
                            Chat History
                        </Box>
                        {[...conversations]
                            .sort(
                                (a, b) =>
                                    new Date(b.updatedAt).getTime() -
                                    new Date(a.updatedAt).getTime()
                            )
                            .map((c) => (
                                <div
                                    key={c.conversationId}
                                    style={{
                                        display: "flex",
                                        alignItems: "center",
                                        gap: 4,
                                        padding: "6px 8px",
                                        borderRadius: 8,
                                        cursor: "pointer",
                                        background:
                                            c.conversationId === activeId
                                                ? "rgba(0,115,187,0.08)"
                                                : "transparent",
                                        borderLeft:
                                            c.conversationId === activeId
                                                ? "3px solid #0972d3"
                                                : "3px solid transparent",
                                    }}
                                    onClick={() => handleLoad(c.conversationId)}
                                    role="button"
                                    tabIndex={0}
                                    onKeyDown={(e) =>
                                        e.key === "Enter" && handleLoad(c.conversationId)
                                    }
                                >
                                    <div style={{ flex: 1, overflow: "hidden" }}>
                                        <div
                                            style={{
                                                fontSize: 13,
                                                fontWeight:
                                                    c.conversationId === activeId ? 600 : 400,
                                                whiteSpace: "nowrap",
                                                overflow: "hidden",
                                                textOverflow: "ellipsis",
                                            }}
                                        >
                                            {c.title || "Untitled"}
                                        </div>
                                        <div style={{ fontSize: 11, color: "#687078" }}>
                                            {new Date(c.updatedAt).toLocaleDateString()} ·{" "}
                                            {c.messageCount} msgs
                                        </div>
                                    </div>
                                    <Button
                                        variant="icon"
                                        iconName="remove"
                                        ariaLabel={`Delete ${c.title || "conversation"}`}
                                        onClick={(e) => {
                                            e.stopPropagation();
                                            remove(c.conversationId);
                                        }}
                                    />
                                </div>
                            ))}
                    </SpaceBetween>
                </Box>
            )}
        </SpaceBetween>
    );
};

export default SideBar;
