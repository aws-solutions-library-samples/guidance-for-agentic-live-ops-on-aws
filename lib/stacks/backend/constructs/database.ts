import { RemovalPolicy } from "aws-cdk-lib";
import { AttributeType, TableV2 } from "aws-cdk-lib/aws-dynamodb";
import { Construct } from "constructs";

export class Database extends Construct {
    public readonly eventsTable: TableV2;
    public readonly liveMetricsTable: TableV2;
    public readonly reportsTable: TableV2;
    public readonly patternRulesTable: TableV2;
    public readonly metricsSummaryTable: TableV2;
    public readonly conversationsTable: TableV2;
    public readonly agentConfigTable: TableV2;

    constructor(scope: Construct, id: string) {
        super(scope, id);

        const eventsTable = new TableV2(this, "eventsTable", {
            partitionKey: {
                name: "request_id",
                type: AttributeType.STRING,
            },
            sortKey: {
                name: "entity_type_timestamp",
                type: AttributeType.STRING,
            },
            pointInTimeRecovery: true,
            removalPolicy: RemovalPolicy.DESTROY,
        });

        // Real-time sliding window metrics from game events (TTL-enabled)
        // PK: metric_key (e.g. "battle_errors#1700000000"), SK: dimension (e.g. "platform#android")
        const liveMetricsTable = new TableV2(this, "liveMetricsTable", {
            partitionKey: {
                name: "metric_key",
                type: AttributeType.STRING,
            },
            sortKey: {
                name: "dimension",
                type: AttributeType.STRING,
            },
            timeToLiveAttribute: "ttl",
            removalPolicy: RemovalPolicy.DESTROY,
            globalSecondaryIndexes: [
                {
                    indexName: "gsi-dimension",
                    partitionKey: { name: "dimension", type: AttributeType.STRING },
                    sortKey: { name: "metric_key", type: AttributeType.STRING },
                },
            ],
        });

        // Reports generated by proactive analysis agents
        const reportsTable = new TableV2(this, "reportsTable", {
            partitionKey: {
                name: "report_id",
                type: AttributeType.STRING,
            },
            sortKey: {
                name: "created_at",
                type: AttributeType.STRING,
            },
            timeToLiveAttribute: "ttl",
            removalPolicy: RemovalPolicy.DESTROY,
            globalSecondaryIndexes: [
                {
                    indexName: "gsi-all-by-time",
                    partitionKey: { name: "gsi_pk", type: AttributeType.STRING },
                    sortKey: { name: "created_at", type: AttributeType.STRING },
                },
            ],
        });

        // Configurable pattern detection rules and thresholds
        const patternRulesTable = new TableV2(this, "patternRulesTable", {
            partitionKey: {
                name: "rule_id",
                type: AttributeType.STRING,
            },
            removalPolicy: RemovalPolicy.DESTROY,
        });

        this.eventsTable = eventsTable;
        this.liveMetricsTable = liveMetricsTable;
        this.reportsTable = reportsTable;
        this.patternRulesTable = patternRulesTable;

        // Pre-aggregated metrics summary — one row per event_type, updated atomically
        // by the pattern detector on each batch. The monitor API queries this instead
        // of scanning the full live_metrics table.
        // PK: event_type (e.g. "battle_error"), no SK needed
        const metricsSummaryTable = new TableV2(this, "metricsSummaryTable", {
            partitionKey: {
                name: "event_type",
                type: AttributeType.STRING,
            },
            timeToLiveAttribute: "ttl",
            removalPolicy: RemovalPolicy.DESTROY,
        });

        this.metricsSummaryTable = metricsSummaryTable;

        // Saved conversations per user — stores full chat history
        // PK: userId (Cognito sub), SK: conversationId (UUID)
        const conversationsTable = new TableV2(this, "conversationsTable", {
            partitionKey: {
                name: "userId",
                type: AttributeType.STRING,
            },
            sortKey: {
                name: "conversationId",
                type: AttributeType.STRING,
            },
            pointInTimeRecovery: true,
            removalPolicy: RemovalPolicy.DESTROY,
        });

        this.conversationsTable = conversationsTable;

        // Dynamic agent configuration cache — one row per sub-agent definition
        // PK: agent_id (e.g. "performance_metrics")
        // Items auto-expire via TTL so stale configs don't linger.
        // The factory writes defaults here on first load; the Config API refreshes TTL on writes.
        const agentConfigTable = new TableV2(this, "agentConfigTable", {
            partitionKey: {
                name: "agent_id",
                type: AttributeType.STRING,
            },
            timeToLiveAttribute: "expires_at",
            removalPolicy: RemovalPolicy.DESTROY,
        });

        this.agentConfigTable = agentConfigTable;
    }
}
